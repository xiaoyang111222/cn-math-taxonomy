def py_str(s):
    return json.dumps(s, ensure_ascii=False)

def fmt_qs(qs):
    lines = []
    for p, a, w, e in qs:
        lines.append("    (%s, %s, [%s, %s, %s], %s)," % (
            py_str(p), py_str(a), py_str(w[0]), py_str(w[1]), py_str(w[2]), py_str(e)))
    return "\n".join(lines)

