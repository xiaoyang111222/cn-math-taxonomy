    book = tail.split(".", 1)[0]
    if book in ("B1", "B2"):
        status = TEXT_STATUS
    elif book == "S1":
        status = S1_TEXT_STATUS
    elif book == "S2":
        status = S2_TEXT_STATUS
    elif book == "S3":
        status = S3_TEXT_STATUS
    else:
        raise KeyError(tail)
    if tail in ABSORB_XUEYE:
        status += XUEYE_STATUS_EXTRA
    return status


