def junior_style(a, b, t):
    return "教学上宜先%s，%s。%s可以凭题面单独判断，这条 soft 不是掌握门槛。" % (a, b, t)


def main():
    dry = "--dry-run" in sys.argv
    with open(os.path.join(ROOT, "data", "topics.json"), encoding="utf-8") as f:
        topics = {t["id"]: t for t in json.load(f)}
    path = os.path.join(ROOT, "data", "dependencies.json")
    with open(path, encoding="utf-8") as f:
        deps = json.load(f)

    new = []
    for to, frm, a, b, t in CROSS_AND_JUNIOR:
        new.append(("cnd_" + (to if to[0] == "j" else to), "cnd_" + frm,
                    junior_style(a, b, t)))
    for to, frm, basis in PRIMARY_SPIRAL:
        n_to, n_frm = topics["cnd_" + to]["name"], topics["cnd_" + frm]["name"]
        new.append(("cnd_" + to, "cnd_" + frm,
                    "按统编版道德与法治螺旋式编排的主题递进，先学「%s」，再学「%s」：%s。" % (n_frm, n_to, basis)))

    existing = {(e["topicId"], e["prerequisiteId"]): e for e in deps}
    errors = []
    todo = []
    seen = set()
    for to, frm, reason in new:
        if to not in topics or frm not in topics:
            errors.append("端点不存在：%s <- %s" % (to, frm))
            continue
        if to == frm:
            errors.append("自环：%s" % to)
            continue
        if (to, frm) in seen:
            errors.append("本脚本内重复：%s <- %s" % (to, frm))
            continue
        seen.add((to, frm))
        old = existing.get((to, frm))
        if old is not None:
            if old["reason"] != reason or old["strength"] != "soft":
                errors.append("与已有边重复且内容不同：%s <- %s" % (to, frm))
            continue
        todo.append({"topicId": to, "prerequisiteId": frm, "strength": "soft", "reason": reason})

    adj = defaultdict(list)
    for e in deps + todo:
        adj[e["topicId"]].append(e["prerequisiteId"])
    color = {}
    for s in list(adj):
        if s in color:
            continue
        stack = [(s, iter(adj[s]))]
        color[s] = 1
        while stack:
            node, it = stack[-1]
            nxt = next(it, None)
            if nxt is None:
                color[node] = 2
                stack.pop()
                continue
            c = color.get(nxt, 0)
            if c == 1:
                errors.append("成环：经过 %s -> %s" % (node, nxt))
            elif c == 0:
                color[nxt] = 1
                stack.append((nxt, iter(adj[nxt])))
    if errors:
        for m in errors:
            print(m, file=sys.stderr)
        return 1
    print("计划新增 %d 条（脚本内共 %d 条，已存在跳过 %d 条）" % (len(todo), len(new), len(new) - len(todo)))
    if dry or not todo:
        return 0
    with open(path, "w", encoding="utf-8") as f:
        json.dump(deps + todo, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
